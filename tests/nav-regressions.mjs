import assert from 'node:assert/strict';
import fs from 'node:fs';
import vm from 'node:vm';
const html=fs.readFileSync(new URL('../index.html',import.meta.url),'utf8');
assert.ok(html.includes('list.setPointerCapture(e.pointerId)'),'reorder capture must remain on the stable list');
assert.ok(!html.includes('b.setPointerCapture(e.pointerId)'),'moving handles must not own capture');
assert.ok(html.includes('list.onpointercancel=stop;list.onlostpointercapture=stop'),'cancel and lost capture clean up');
assert.ok(html.includes('function navOrderClose(){navDragStop();'),'Back/cancel clean up');
assert.ok(html.includes('d.ghost.style.top=(y-d.offset)'),'row follows the held finger');
const fn=html.match(/function swipeTarget\(dx\)\{[^\n]+\}/)?.[0];assert.ok(fn);
let buttons=[];
const ctx=vm.createContext({ui:{tab:'b'},document:{querySelectorAll:()=>buttons}});vm.runInContext(fn,ctx);
const set=(rows,current)=>{buttons=rows.map(([tab,left,width=40])=>({dataset:{tab},getBoundingClientRect:()=>({left,width})}));ctx.ui.tab=current;};
set([['a',0],['b',50],['c',100]],'b');assert.equal(ctx.swipeTarget(-120),'c');assert.equal(ctx.swipeTarget(120),'a');
set([['a',100],['b',50],['c',0]],'b');assert.equal(ctx.swipeTarget(-120),'a');assert.equal(ctx.swipeTarget(120),'c');
set([['a',75],['b',0],['c',150]],'a');assert.equal(ctx.swipeTarget(-120),'c');assert.equal(ctx.swipeTarget(120),'b');
set([['a',0],['b',50,0],['c',100]],'a');assert.equal(ctx.swipeTarget(-120),'c');assert.equal(ctx.swipeTarget(120),null);
set([['a',0]],'a');assert.equal(ctx.swipeTarget(-120),null);assert.equal(ctx.swipeTarget(120),null);
set([['a',0],['b',50]],'perf');assert.equal(ctx.swipeTarget(-120),null);
assert.equal((html.match(/const target=swipeTarget\(dx\)/g)||[]).length,2,'both ordinary and rapid second watch swipes must use physical positions');
console.log('PASS stable drag capture/cleanup/finger geometry and physical LTR/RTL/reordered/hidden/edge/no-wrap swipe targets');
